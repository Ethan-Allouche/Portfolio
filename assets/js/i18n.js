/** Fabrique un traducteur d'interface pour une langue. */
export function translator(lang) {
  const dict = UI[lang] || UI.en;
  return (key, vars) => {
    let s = dict[key] ?? UI.en[key] ?? key;
    if (vars) for (const k in vars) s = s.replace('{' + k + '}', vars[k]);
    return s;
  };
}
