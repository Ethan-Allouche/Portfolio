export const LANGS = ['he', 'fr', 'en'];
export const DIR = { he: 'rtl', fr: 'ltr', en: 'ltr' };
export const SHORT = { he: 'עב', fr: 'FR', en: 'EN' };
export const NAMES = { he: 'עברית', fr: 'Français', en: 'English' };

const KEY = 'portfolio.lang';

/** Langue à afficher : choix explicite (?lang=), puis choix mémorisé, puis langue du navigateur. */
export function detectLang() {
  const asked = new URLSearchParams(location.search).get('lang');
  if (LANGS.includes(asked)) return asked;
  try {
    const saved = localStorage.getItem(KEY);
    if (LANGS.includes(saved)) return saved;
  } catch {}
  const prefs = navigator.languages && navigator.languages.length ? navigator.languages : [navigator.language || ''];
  for (const p of prefs) {
    const code = String(p).toLowerCase().split('-')[0];
    if (code === 'iw') return 'he';
    if (LANGS.includes(code)) return code;
  }
  return 'en';
}
export function rememberLang(lang) {
  try { localStorage.setItem(KEY, lang); } catch {}
}

/** Texte d'un champ traduit ({fr, en, he}) dans la langue voulue, avec repli. */
export function pick(v, lang) {
  if (v == null) return '';
  if (typeof v !== 'object') return String(v);
  return v[lang] || v.fr || v.en || v.he || '';
}

